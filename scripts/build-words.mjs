// Builds src/words.js from the `word-list` package (MIT, Sindre Sorhus).
// Output is a classic script so the game runs straight from file:// with no server.
import fs from 'node:fs';
import wordListPath from 'word-list'; // default export: absolute path to words.txt

const MIN = 3, MAX = 12;

const words = fs.readFileSync(wordListPath, 'utf8')
  .split('\n')
  .map(w => w.trim().toUpperCase())
  .filter(w => w.length >= MIN && w.length <= MAX && /^[A-Z]+$/.test(w));

const out = `// Generated by scripts/build-words.mjs: do not edit.\n` +
  `// Source: word-list (MIT) by Sindre Sorhus. ${words.length} words, ${MIN}-${MAX} letters.\n` +
  `(function (root) { root.GW_WORDS = ${JSON.stringify(words.join(' '))}; })(typeof window !== 'undefined' ? window : globalThis);\n`;

fs.writeFileSync(new URL('../src/words.js', import.meta.url), out);
console.log(`Wrote ${words.length} words.`);
